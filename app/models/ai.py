import uuid
from datetime import datetime, timezone
from app.extensions import db

class AIResponse(db.Model):
    """Database model for storing AI LLM-generated explanations and remediations."""
    __tablename__ = 'ai_responses'

    id = db.Column(db.Integer, primary_key=True)
    uuid = db.Column(db.String(36), default=lambda: str(uuid.uuid4()), unique=True, index=True, nullable=False)
    prompt = db.Column(db.Text, nullable=False)
    response_text = db.Column(db.Text, nullable=False)
    model_used = db.Column(db.String(100), nullable=False)  # e.g., 'gemini-3.5-flash'
    created_at = db.Column(db.DateTime, default=lambda: datetime.now(timezone.utc), nullable=False)
    
    # Foreign Keys (Nullable depending on context - associated with a specific scan or report)
    scan_id = db.Column(db.Integer, db.ForeignKey('scans.id', ondelete='SET NULL'), index=True, nullable=True)
    report_id = db.Column(db.Integer, db.ForeignKey('reports.id', ondelete='SET NULL'), index=True, nullable=True)
    network_scan_id = db.Column(db.Integer, db.ForeignKey('network_scans.id', ondelete='SET NULL'), index=True, nullable=True)

    def __repr__(self):
        return f"<AIResponse {self.uuid} generated by {self.model_used}>"
